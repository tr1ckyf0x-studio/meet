export type Key = keyof typeof ru;
const DICTS: Record<Lang, Dict> = { ru, en };

function pluralIndex(lang: Lang, n: number): number {
  if (lang === "en") return n === 1 ? 0 : 1;
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 0;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 1;
  return 2;
}

/** Translates a key; `{name}` takes a value, `{n|one|few|many}` picks a plural form by the number `n`. */
export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  return s.replace(/\{(\w+)((?:\|[^|}]*)+)?\}/g, (_, name: string, forms?: string) => {
    const v = vars[name];
    if (forms) {
      const list = forms.slice(1).split("|");
      return list[Math.min(pluralIndex(lang, Number(v)), list.length - 1)] ?? "";
    }
    return v === undefined ? "" : String(v);
  });
}

export function pickLang(header: string | undefined | null): Lang {
  if (!header) return "en";
  for (const part of header.split(",")) {
    const code = part.trim().slice(0, 2).toLowerCase();
    if (code === "ru") return "ru";
    if (code === "en") return "en";
  }
  return "en";
}

/** A readable reason for an error code (FetchError codes and the like). */
export function errText(lang: Lang, code: string | null | undefined): string {
  const key = `e_${code ?? "failed"}`;
  return key in ru ? t(lang, key as Key) : t(lang, "e_failed");
}

export const isLang = (x: unknown): x is Lang => x === "ru" || x === "en";
